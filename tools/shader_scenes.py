def tool_sets(key):
    """Whether game_environment sets or removes `key` whatever --env says (a scratch folder, the frozen scene, the
    staged pack, the display, no audio, no trace file)."""
    sentinel = "\0--env"
    return game_environment(Path("/scene-suite-env-probe"), {key: sentinel}).get(key) != sentinel


def env_pairs(values):
    """--env KEY=VALUE values as a dict; a value without =, and a key the tool sets itself (tool_sets), are
    refused."""
    out = {}
    for value in values:
        key, eq, item = value.partition("=")
        if not eq or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key):
            raise SystemExit(f"--env {value!r}: expected KEY=VALUE")
        if tool_sets(key):
            raise SystemExit(f"--env {key}: the tool sets it for every game; it can't be changed")
        out[key] = item
    return out


class Parser(argparse.ArgumentParser):
    """argparse with a wrong command line exiting SETUP_FAILED, not argparse's 2 (which is INVALID here)."""

    def error(self, message):
        self.print_usage(sys.stderr)
        self.exit(SETUP_FAILED, f"{self.prog}: error: {message}\n")


def parser():
    p = Parser(description=__doc__.split("\n\n")[0], epilog=__doc__.split("\n\n")[-1].strip())
    sub = p.add_subparsers(dest="step", required=True, parser_class=Parser)
    steps = {
        "check": "check the scene file and print the commands of each view",
        "world": "generate the shared world with one Sunrise build",
        "capture": "take one side's pictures of each --pack with one Sunrise build",
        "compare": "compare base and head pixel for pixel and write the report",
        "run": "world (unless it exists, with the base build), base and head captures of none and each --pack, "
               "then compare",
    }
    for name, text in steps.items():
        s = sub.add_parser(name, help=text, description=text)
        s.add_argument("--scenes", default=str(SCENES),
                       help="the scene file (default: tools/shader-scenes/scenes.json)")
        if name == "check":
            continue
        s.add_argument("--out", required=True, help="the output folder; every run writes only inside it")
        if name in ("compare", "run"):
            s.add_argument("--jobs", type=int, default=2,
                           help="games at once (run), and picture comparisons at once (default 2)")
        if name == "compare":
            continue
        s.add_argument("--replace", action="store_true", help="run again over this tool's earlier output")
        s.add_argument("--resources", default=None, help="prepared resources (default: .local/sunrise-client/26.3)")
        s.add_argument("--display", choices=("headless", "current"), default="headless",
                       help="headless: each game in a gamescope headless display of its own, of the scene's size "
                            "(default); current: the desktop's display")
        if name in ("world", "capture"):
            s.add_argument("--bin-dir", required=True, help="the folder holding the build's sunrise-client and "
                                                            "sunrise-ctl")
        if name == "capture":
            s.add_argument("--side", choices=SIDES, required=True, help="which side these pictures are")
            s.add_argument("--env", action="append", default=[],
                           help="KEY=VALUE set in this side's game environment (repeatable)")
        if name == "run":
            for side in SIDES:
                s.add_argument(f"--{side}-bin-dir", required=True,
                               help=f"the folder holding the {side} build's sunrise-client and sunrise-ctl")
                s.add_argument(f"--{side}-env", action="append", default=[],
                               help=f"KEY=VALUE set in the {side} game's environment (repeatable)")
        if name in ("capture", "run"):
            s.add_argument("--pack", action="append", default=[],
                           help="a shader pack zip or folder, or none (repeatable; `run` always adds none)")
    return p


def absolute_paths(args, cwd=None):
    """Makes every path argument absolute against the caller's folder: each game runs with its own game folder as
    its working directory, where a relative --out or --pack would point somewhere else."""
    base = Path(cwd or os.getcwd())

    def absolute(value):
        return value if value is None or value == "none" else str((base / value).resolve())
    for key in ("scenes", "out", "resources", "bin_dir", "base_bin_dir", "head_bin_dir"):
        if getattr(args, key, None) is not None:
            setattr(args, key, absolute(getattr(args, key)))
    if hasattr(args, "pack"):
        args.pack = [absolute(p) for p in args.pack]
    return args


def main(argv=None):
    """Exit status: 0 every view valid and equal, 1 the comparison completed and some valid view differs, 2 some
    view invalid or missing (or, for `capture`, not every view recorded), 3 the run could not be set up or the
    command line is wrong."""
    try:
        return _main(argv)
    except OSError as error:
        # A file the setup reads or writes outside a game (a game's own failures are a run's notes, not this).
        print(f"setup failed: {error}", file=sys.stderr)
        return SETUP_FAILED
    except SystemExit as stop:
        if isinstance(stop.code, str):
            print(stop.code, file=sys.stderr)
            return SETUP_FAILED
        if stop.code == SETUP_FAILED:  # a wrong command line (Parser.error)
            return SETUP_FAILED
        raise


def _main(argv):
    args = absolute_paths(parser().parse_args(argv))
    try:
        scenes = load_scenes(args.scenes)
        packs = list(getattr(args, "pack", []))
        if args.step == "run" and "none" not in packs:
            packs = ["none", *packs]
        keys = [pack_key(pack) for pack in packs]
        twice = sorted({k for k in keys if keys.count(k) > 1})
        if twice:
            raise SceneError(f"--pack: several packs share the folder name {', '.join(twice)}")
    except SceneError as error:
        raise SystemExit(f"scene error: {error}")
    missing = [p for p in packs if p != "none" and not Path(p).exists()]
    if missing:
        raise SystemExit(f"pack {missing[0]} not found")
    if args.step == "check":
        for view in scenes["views"]:
            print(view["name"])
            for line in view_commands(view) + setup_commands(view):
                print(f"  {line}")
        return 0
    try:
        Path(args.out).mkdir(parents=True, exist_ok=True)
    except OSError as error:
        raise SystemExit(f"--out {args.out}: not a folder this tool can write in ({error})") from None
    if args.step == "compare":
        return summary(compare(args.out, scenes, jobs=args.jobs))
    from tools import lab
    args.resources = args.resources or str(lab.RESOURCES)
    if not Path(args.resources).exists():
        raise SystemExit(f"{args.resources} not found (resources: tools/prepare_native_client.py)")
    if args.step == "world":
        run_world(args, scenes, args.bin_dir)
        return 0
    if not packs:
        raise SystemExit("no --pack given")
    if args.step == "capture":
        records = [run_capture(args, scenes, args.side, args.bin_dir, env_pairs(args.env), p) for p in packs]
        empty = [pack_key(p) for p, r in zip(packs, records) if len(r["views"]) < len(scenes["views"])]
        for key in empty:
            print(f"{args.side} {key}: not every view was captured", file=sys.stderr)
        return INVALID if empty else 0
    sides = {side: (getattr(args, f"{side}_bin_dir"), env_pairs(getattr(args, f"{side}_env"))) for side in SIDES}
    if world_generation(args.out) is None:
        run_world(args, scenes, sides["base"][0])
    # One task per side and pack, interleaved so that with two jobs a base and a head game run side by side.
    order = [(side, p) for p in packs for side in SIDES]
    with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, args.jobs)) as pool:
        list(pool.map(lambda t: run_capture(args, scenes, t[0], *sides[t[0]], t[1]), order))
    return summary(compare(args.out, scenes, keys, jobs=args.jobs))


if __name__ == "__main__":
    sys.exit(main())
