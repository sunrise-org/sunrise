def fresh_folder(folder, replace, mark=RUN_MARK):
    """A fresh folder for a run. An existing one is only removed with --replace, and only when it carries this
    tool's mark (a folder some earlier run of this tool made)."""
    folder = Path(folder)
    if folder.exists():
        if not replace:
            raise SystemExit(f"{folder} exists: pass --replace to run it again")
        if not (folder / mark).exists():
            raise SystemExit(f"{folder} was not made by this tool; not removing it")
        shutil.rmtree(folder)
    folder.mkdir(parents=True)
    (folder / mark).write_text("")
    return folder


def world_generation(out):
    """The published world: the generation OUT/world/current.json points at, as its generation.json records it (its
    generation id, the scene hash it was made for, the build that made it and its save's digest), with "save", the
    folder of its save. None when nothing is published; a pointer or record that can't be read is refused."""
    world = Path(out) / "world"
    pointer = world / "current.json"
    if not pointer.exists():
        if (world / "generation.json").exists():
            raise SystemExit(f"{world} holds a world published by an earlier version of this tool (generation.json "
                             "without current.json): run `world --replace`")
        return None
    try:
        world_id = json.loads(pointer.read_text())["world_id"]
        if not isinstance(world_id, str) or not re.fullmatch(r"[0-9a-f]{32}", world_id):
            raise ValueError(f"world_id {world_id!r}")
        folder = world / "generations" / world_id
        generation = json.loads((folder / "generation.json").read_text())
        if not isinstance(generation, dict) or generation.get("world_id") != world_id or not all(
                isinstance(generation.get(k), str) for k in ("scene_hash", "save_sha256")):
            raise ValueError("generation.json is not this generation's record")
    except (OSError, ValueError, KeyError, TypeError) as error:
        raise SystemExit(f"{world}: the published world can't be read ({error}): run `world --replace`") from None
    return {**generation, "save": folder / WORLD}


def copy_world(out, game_dir, scenes):
    """Copies the published world into a game's saves/ and returns the identity a run records with its pictures
    ({"world_id", "save_sha256", "scene_hash"}), so the report pairs only pictures of the same world and scene. The
    staged copy is hashed and must be the save generation.json recorded when the world was published: a save edited
    or replaced since is refused, as is a world made for another scene definition (its chunks and saved camera are
    for other views)."""
    generation = world_generation(out)
    if generation is None or not (generation["save"] / "level.dat").exists():
        raise SystemExit(f"{Path(out) / 'world'} has no published world: run `world` first")
    source = generation["save"]
    if generation["scene_hash"] != scene_hash(scenes):
        raise SystemExit(f"{Path(out) / 'world'} was generated for another scene definition: run `world --replace`")
    staged = game_dir / "saves" / WORLD
    shutil.copytree(source, staged, ignore=shutil.ignore_patterns("session.lock"))
    digest = staged_digest(staged)
    if digest != generation["save_sha256"]:
        raise SystemExit(f"{source} is not the save its generation.json records (its digest changed since it was "
                         "published): run `world --replace`")
    return {"world_id": generation["world_id"], "save_sha256": digest, "scene_hash": generation["scene_hash"]}


def write_run(folder, record):
    (Path(folder) / "run.json").write_text(json.dumps(record, indent=2) + "\n")


class Sunrise:
    """One Sunrise game driven through sunrise-ctl."""

    def __init__(self, ctl, socket, env):
        self.ctl, self.socket, self.env = ctl, socket, env

    def __call__(self, *words, check=True, timeout=600):
        done = subprocess.run([str(self.ctl), "--socket", str(self.socket), *map(str, words)], env=self.env,
                              capture_output=True, text=True, timeout=timeout)
        lines = [l for l in done.stdout.splitlines() if l.startswith("{")]
        reply = json.loads(lines[-1]) if lines else {"error": done.stderr.strip() or "no reply"}
        if check and "error" in reply:
            raise RuntimeError(f"sunrise-ctl {' '.join(map(str, words))}: {reply['error']}")
        return reply

    def command(self, line):
        reply = self("command", line, check=False)
        return "error" not in reply and reply.get("success", False)


def sunrise_camera(state):
    player = state.get("player") or {}
    weather = state.get("weather") or {}
    return {"dimension": state.get("dimension"), "pos": player.get("position"), "yaw": player.get("yaw"),
            "pitch": player.get("pitch"), "screen": state.get("screen"), "gamemode": state.get("gamemode"),
            "spectator": state.get("gamemode") == "spectator",
            "day_time": (state.get("time") or {}).get("day_time"), "raining": weather.get("raining"),
            "thundering": weather.get("thundering")}


def sunrise_frozen(reply):
    """Whether Sunrise reports the game frozen, from its `tick query` reply: True or False from vanilla's status
    line, None when the command failed or no status line came back."""
    if "error" in reply or not reply.get("success"):
        return None
    for line in reversed([str(line) for line in reply.get("chat", [])]):
        if TICK_FROZEN in line:
            return True
        if any(text in line for text in TICK_NOT_FROZEN):
            return False
    return None


def sunrise_settings(status, options):
    """The drawing settings Sunrise holds: the render distance it draws (status) and the simulation distance and
    field of view of its options (`options-get`)."""
    values = (options.get("options") or {})
    return {"render_distance": status.get("render_distance"),
            "simulation_distance": (values.get("simulationDistance") or {}).get("value"),
            "fov": (values.get("fov") or {}).get("value")}


# What the render thread logs when the teleport's feedback reaches the chat: vanilla's
# commands.teleport.success.location.single ("Teleported %s to %s, %s, %s", assets/minecraft/lang/en_us.json) after
# Sunrise's `[CHAT] ` (crates/sunrise-client-render/src/chat.rs). The server sends it after the teleport, so the
# client has applied the move (its dimension change among it) when it logs the line.
MOVE_MARK = "[CHAT] Teleported "


def pack_events(log_text, name):
    """What the log shows of the pack, in order: ("move",) for each teleport's feedback line (MOVE_MARK),
    ("programs", N) for `shader pack <name>: N programs ...` and ("off", why) for `shader pack <name>: turned off:
    why`. Sunrise loads a pack when the world opens and again at each dimension change."""
    prefix = f"shader pack {name}: "
    out = []
    for line in log_text.splitlines():
        if MOVE_MARK in line:
            out.append(("move",))
            continue
        at = line.find(prefix)
        if at < 0:
            continue
        rest = line[at + len(prefix):]
        loaded = re.match(r"(\d+) programs\b", rest)
        if loaded:
            out.append(("programs", int(loaded.group(1))))
        elif rest.startswith("turned off: "):
            out.append(("off", rest[len("turned off: "):]))
    return out


AWAITED_AT_MOVE = ("a load of the dimension before was still awaited at the move into this dimension: the loads "
                   "after it can't be told apart")
NO_MOVE_LINE = "the move into this dimension showed no feedback line: its loads can't be placed"


class PackWatch:
    """Active-pack evidence for each capture interval, bound to the move that asked for it. The log is read in
    order: each view's teleport shows as its feedback line (a "move"), and the pack loads that finish or fail come
    between them. A view that changes dimension awaits one load logged after its own move line: the client logged
    that line after applying the move, so a load logged before it (a reload in the dimension before, however late
    it ran) can never stand in for it. An awaited load stays awaited across views of the same dimension, so a load
    that timed out is still missing at the next capture there; a move to another dimension while one is still
    awaited leaves the loads after it impossible to tell apart, and every capture in that dimension is invalid. A
    load that nothing awaits came at a time the log can't place: the capture before it (the line may have been
    written late) and the next one are invalid. Before a capture its move line must be there, every awaited load
    must have come and the last must be running; a load between a capture's start and its reply makes that capture
    invalid.

    The load line (crates/sunrise-client-gameplay/src/game/interface/shader_packs.rs, shader_pack_inputs) names the
    pack, its programs and the build's time, not the dimension the build was for, so a load is placed by its
    order. The client polls a finished build before it checks the dimension, in the same frame: a build of the
    dimension before that finishes in the frame the move is applied logs its line after the move line, is
    installed, and the client starts the new dimension's build at once (load_shader_pack drops the installed
    pack while it builds). So that case always logs a second load after the move line, which nothing awaits and
    which invalidates the capture whenever it lands (before it, during it, or before the next one); and while the
    new build runs no pack is installed, and screenshot-sequence refuses to start (the reply names no running
    pack) or fails when the pack changes while it draws. A missing move line (a teleport whose feedback never
    came) invalidates its own view; when that move changed dimension the loads after it can't be placed, as above.
    A move line no teleport explains (one that came late) invalidates the capture before it and the next one."""

    def __init__(self, read_events, now=time.time, sleep=time.sleep):
        self.read, self.now, self.sleep = read_events, now, sleep
        self.seen = 0  # events taken
        self.moves_seen, self.moves_sent = 0, 0
        self.pending = 0  # loads the current dimension awaits
        self.ambiguous = None  # why the current dimension's loads can't be placed, if they can't
        self.changes = {}  # move number -> whether that move changes dimension
        self.stray = 0  # loads nothing awaited, since the last capture
        self.extra_moves = 0  # move lines no teleport sent explains, since the last capture

    def world_opened(self):
        """The world opens in the saved dimension and loads the pack: the first captures await that load."""
        self.pending += 1

    def move_sent(self, new_dimension):
        """The next teleport is about to be sent; `new_dimension`: it changes dimension (a load is to follow)."""
        self.moves_sent += 1
        self.changes[self.moves_sent] = new_dimension

    def _take(self, events):
        for event in events[self.seen:]:
            self.seen += 1
            if event[0] == "move":
                if self.moves_seen == self.moves_sent:
                    self.extra_moves += 1
                    continue
                self.moves_seen += 1
                if self.changes.get(self.moves_seen):
                    self.ambiguous = AWAITED_AT_MOVE if self.pending > 0 else None
                    self.pending = 1
            elif self.pending:
                self.pending -= 1
            else:
                self.stray += 1

    def _stray_problems(self):
        texts = []
        if self.stray:
            texts.append(f"{self.stray} pack load(s) came that no dimension change asked for")
        if self.extra_moves:
            texts.append(f"{self.extra_moves} teleport feedback line(s) came that no teleport of this view sent")
        self.stray = self.extra_moves = 0
        return texts, [f"{text} after this capture; it may have run during it" for text in texts]

    def before_capture(self, timeout):
        """Returns (problems of this capture, problems of the capture before it)."""
        deadline = self.now() + timeout
        events = self.read()
        self._take(events)
        while (self.moves_seen < self.moves_sent or self.pending) and self.now() < deadline:
            self.sleep(0.5)
            events = self.read()
            self._take(events)
        mine, previous = self._stray_problems()
        if self.moves_seen < self.moves_sent:
            mine.insert(0, "the teleport's feedback never showed in the log")
            # The move is given up: a line that comes later is one no teleport explains. A dimension it changed
            # awaits its load with nothing to place it by.
            for move in range(self.moves_seen + 1, self.moves_sent + 1):
                if self.changes.get(move):
                    self.ambiguous, self.pending = NO_MOVE_LINE, 1
            self.moves_sent = self.moves_seen
        elif self.pending:
            mine.insert(0, "the pack never finished loading in this dimension")
        if self.ambiguous:
            mine.append(self.ambiguous)
        loads = [e for e in events[:self.seen] if e[0] != "move"]
        if loads and loads[-1][0] == "off":
            mine.append(f"the pack was turned off: {loads[-1][1]}")
        return mine, previous

    def after_capture(self):
        """Problems of the capture that just replied: a load (or move) the log shows since its start."""
        events = self.read()
        moved = len(events) - self.seen
        self._take(events)
        self.stray = self.extra_moves = 0
        return [f"{moved} pack event(s) came during the capture"] if moved else []


def wait_loaded(game, view, limit, moved=True):
    """Waits until the camera is in the view's dimension, at its position, and the chunks around it are loaded and
    drawn: tools/perf_bench.py's wait_loaded, the readiness the benchmarks use (`wait-ready` alone can answer
    before loading starts: right after a teleport nothing is queued yet). With `moved` false (the camera stays where
    the last loaded view was) the teleport guard is skipped and only steady, drawn chunks are waited for. True when
    loaded within `limit`."""
    from tools import perf_bench
    # perf_bench appends every status to PERF_BENCH_TRACE's file when the caller's environment set it: this tool
    # writes only under its output folder, so no trace is written.
    perf_bench.TRACE = None
    want = dimension_id(view["dimension"])

    def status(line, timeout=10):
        reply = game(line, timeout=timeout)
        if reply.get("dimension") != want:
            reply = dict(reply, player=None)  # not there yet: wait_loaded starts over
        return reply

    def near(position):
        return max(abs(a - b) for a, b in zip(position, view["pos"])) <= POSITION_EPSILON

    try:
        distance = game("status", timeout=10).get("render_distance") or 0
        perf_bench.wait_loaded(status, near, limit, perf_bench.view_chunks(distance) if moved else 0)
        return True
    except (TimeoutError, RuntimeError, OSError, subprocess.TimeoutExpired):
        return False


def pack_reply_problems(reply, staged_name):
    """What differs between the pack a screenshot-sequence reply says it drew and the one the run staged (None for
    `none`): the reply names the running pack's kind and its path, taken when the sequence started; the sequence
    ends with an error if the pack changes while it draws."""
    pack = reply.get("pack")
    if not isinstance(pack, dict):
        return ["the capture's reply names no pack"]
    if staged_name is None:
        return [] if pack.get("kind") == "none" and pack.get("name") is None else [f"a pack ran: {pack}"]
    name = pack.get("name")
    if pack.get("kind") in (None, "none") or not isinstance(name, str) or Path(name).name != staged_name:
        return [f"the capture drew {pack}, not {staged_name}"]
    return []


def capture(game, scenes, path, limit, view, now=time.time):
    """screenshot-sequence FRAMES STEP_MS PATH, taken again while the game still loads (until `limit`) or after the
    scene changed under it (CAPTURE_ATTEMPTS in all). Returns (reply, attempts)."""
    deadline, attempts, changed = now() + limit, 0, 0
    while True:
        attempts += 1
        reply = game("screenshot-sequence", scenes["frames"], _coordinate(scenes["step_ms"]), path, check=False,
                     timeout=limit + 600)
        error = str(reply.get("error", ""))
        if LOADING_REFUSAL in error and now() < deadline:
            wait_loaded(game, view, max(1.0, deadline - now()), moved=False)
            continue
        if CHANGED_REFUSAL in error and changed + 1 < CAPTURE_ATTEMPTS:
            changed += 1
            continue
        return reply, attempts


def _f32(value):
    """A number as the f32 the game holds it in."""
    return struct.unpack("<f", struct.pack("<f", value))[0]


def sequence_clock(frames, step_ms):
    """The clock screenshot-sequence gives its last frame (docs/agent-control.md, screenshot-sequence): frame n is
    at counter n, (n - 1) x STEP_MS milliseconds and STEP_MS since the frame before (0 on frame 1), elapsed and delta
    in seconds as f32s worked out from the f64 step."""
    step = step_ms / 1000.0
    return {"counter": frames, "elapsed": _f32((frames - 1) * step), "delta": _f32(step) if frames > 1 else 0.0}


def clock_problems(reply, frames, step_ms):
    """What differs between the clock a screenshot-sequence reply says it drew on and the scene's: its frame count
    and step, and the last frame's counter, elapsed and delta, compared exactly at the f32 the game holds them in."""
    problems = []
    if reply.get("frames") != frames or reply.get("step_ms") != step_ms:
        problems.append(f"the capture drew {reply.get('frames')} frames {reply.get('step_ms')} ms apart, the scene "
                        f"asks for {frames} frames {step_ms} ms apart")
    frame = reply.get("frame") if isinstance(reply.get("frame"), dict) else {}
    want = sequence_clock(frames, step_ms)
    for key in ("counter", "elapsed", "delta"):
        got = frame.get(key)
        if isinstance(got, bool) or not isinstance(got, (int, float)) or got != want[key]:
            problems.append(f"the picture's frame {key} is {got}, not {want[key]}")
    return problems


def capture_problems(reply, scenes, staged_name):
    """A screenshot-sequence reply that failed, wrote a picture of another size, drew on another clock or drew
    another pack."""
    if "error" in reply or not reply.get("ok"):
        return [f"screenshot-sequence: {reply.get('error', 'no ok in the reply')}"]
    problems = []
    size = scenes["size"]
    if reply.get("size") != list(size):
        problems.append(f"the picture is {reply.get('size')}, the scene asks for {size[0]}x{size[1]}")
    problems += clock_problems(reply, scenes["frames"], scenes["step_ms"])
    return problems + pack_reply_problems(reply, staged_name)


def capture_view(game, scenes, view, previous, folder, watch, staged_name, expected, new_dimension=False,
                 sleep=time.sleep):
    """Places, loads, settles, checks and captures one view; returns (its record, the problems of the view before
    it, whether it loaded). `new_dimension`: the move changes dimension, so the game loads the pack again."""
    limit = scenes["load_timeout_seconds"]
    watch.move_sent(new_dimension)
    for line in view_commands(view):
        game.command(line)
    ready = wait_loaded(game, view, limit, moved=not same_place(view, previous))
    # Setup runs only in a loaded view: in a late teleport or a half-loaded region it would act on other blocks on
    # each side. A setup that didn't run, or ran in part, leaves the world unlike the other side's for the views
    # after it too (run_views).
    failed, skipped = [], []
    if ready:
        failed = [c for c in setup_commands(view) if not game.command(c)]
        if view["setup"]:
            # Setup changes blocks: wait until they are drawn.
            ready = wait_loaded(game, view, limit, moved=False)
    else:
        skipped = setup_commands(view)
    sleep(settle_time(scenes, view, previous))
    camera = sunrise_camera(game("state"))
    camera["frozen"] = sunrise_frozen(game("command", "tick query", check=False))
    camera["settings"] = sunrise_settings(game("status"), game("options-get", "simulationDistance", "fov"))
    mine, before = watch.before_capture(limit)
    name = f"{view['name']}.png"
    reply, attempts = capture(game, scenes, Path(folder) / name, limit, view)
    # Hashed as soon as the reply says the file is written, before anything else can touch it.
    picture = Path(folder) / name
    digest = sha256_file(picture) if picture.is_file() and "error" not in reply else None
    mine += watch.after_capture()
    after = sunrise_camera(game("state"))
    problems = (camera_problems(view, camera) + settings_problems(expected, camera["settings"])
                + [f"command failed: {c}" for c in failed]
                + [f"setup not run (the view never loaded): {c}" for c in skipped]
                + ([] if ready else ["the view never finished loading"]) + mine
                + capture_problems(reply, scenes, staged_name))
    if after.get("day_time") != camera.get("day_time"):
        problems.append(f"the time moved during the capture: {camera.get('day_time')} to {after.get('day_time')}")
    if digest is None and not any(p.startswith("screenshot-sequence") for p in problems):
        problems.append(f"{name} was not written")
    record = {"camera": camera, "failed_commands": failed, "skipped_commands": skipped,
              "setup_complete": not failed and not skipped, "ready": ready, "attempts": attempts,
              "reply": {k: reply.get(k) for k in ("pack", "frame", "frames", "step_ms", "size", "error")},
              "picture": name if digest else None, "sha256": digest, "problems": problems}
    return record, before, ready


def run_views(game, scenes, folder, watch, staged_name, expected, dimension, views, side="", key=""):
    """Captures every view in order in one game (opened in `dimension`) into `views` ({view: record}), each as soon
    as it is taken, so the views before a game that stops answering keep their records. A view whose problems the
    next view's evidence found gets them too; once a view's setup did not run fully, every later view is invalid,
    since the world it draws may differ from the other side's."""
    previous, last, broken = None, None, None
    for view in scenes["views"]:
        moved = bool(staged_name) and view["dimension"] != dimension
        dimension = view["dimension"]
        entry, before, ready = capture_view(game, scenes, view, previous, folder, watch, staged_name, expected,
                                            new_dimension=moved)
        if before and last is not None:
            views[last]["problems"] += before
        if broken is not None:
            entry["problems"].append(f"the setup of view {broken} did not run fully: the world may differ from the "
                                     "other side's")
        elif not entry["setup_complete"]:
            broken = view["name"]
        views[view["name"]] = entry
        previous, last = (view if ready else None), view["name"]
        print(f"{side} {key} {view['name']}: {entry['problems'] or 'ok'}", flush=True)
    return views


def display_command(args, scenes, command):
    """The game's command, inside a headless gamescope display of the scene's size unless --display current: the
    window gets exactly that size whatever the desktop's compositor does, and nothing opens on the desktop."""
    if args.display == "current":
        return command
    if not shutil.which("gamescope"):
        raise SystemExit("--display headless needs gamescope (or pass --display current)")
    width, height = map(str, scenes["size"])
    return ["gamescope", "--backend", "headless", "-W", width, "-H", height, "-w", width, "-h", height,
            "--", *command]


def game_environment(folder, extra_env):
    """The game's environment: the side's own --env values, then scratch home, launcher home and all four XDG
    folders under the run folder, no audio, SUNRISE_STILL=1 (a frozen scene draws the same frame every run), and no
    shader pack, Wayland display or PERF_BENCH_TRACE inherited from the caller (the game must use gamescope's X
    display). The tool's own values (lab.game_env's among them) are set last, so no --env value replaces them."""
    from tools import lab
    env = dict(os.environ)
    env.update(extra_env)
    for key in ("SUNRISE_SHADER_PACK", "WAYLAND_DISPLAY", "PERF_BENCH_TRACE"):
        env.pop(key, None)
    env = lab.game_env(env, SUNRISE_HOME=folder / "home", SUNRISE_LAUNCHER_HOME=folder / "launcher-home",
                       **{f"XDG_{kind}_HOME": folder / f"xdg-{kind.lower()}"
                          for kind in ("CONFIG", "DATA", "CACHE", "STATE")})
    env["SUNRISE_STILL"] = "1"
    return env


def start_game(args, scenes, command, env, log_path, cwd):
    with open(log_path, "w") as log:
        return subprocess.Popen(display_command(args, scenes, command), cwd=cwd, env=env, stdout=log,
                                stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL)


def stop_game(proc, timeout=60):
    try:
        proc.wait(timeout=timeout)
    except subprocess.TimeoutExpired:
        proc.terminate()
        try:
            proc.wait(timeout=30)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait()


def wait_for_socket(game, proc, timeout):
    deadline = time.time() + timeout
    while time.time() < deadline and proc.poll() is None:
        if "error" not in game("hello", check=False, timeout=30):
            return True
        time.sleep(0.5)
    return False


def binaries(bin_dir):
    """sunrise-client and sunrise-ctl of one build's folder (each side drives its game with its own sunrise-ctl)."""
    from tools import lab
    client, ctl = lab.binary(bin_dir, "sunrise-client"), lab.binary(bin_dir, "sunrise-ctl")
    for path in (client, ctl):
        if not Path(path).is_file():
            raise SystemExit(f"{path} not found (cargo build --profile fast -p sunrise-game --bin sunrise-client "
                             "-p sunrise-client-lib --bin sunrise-ctl, then pass the folder they are in)")
    return Path(client), Path(ctl)


def find_descendant(pid, exe, proc=Path("/proc")):
    """The pid of the first process under `pid` (itself included) running `exe`, from /proc's children lists; None
    when there is none."""
    want = os.path.realpath(exe)
    queue, seen = [pid], set()
    while queue:
        current = queue.pop(0)
        if current in seen:
            continue
        seen.add(current)
        try:
            if os.path.realpath(proc / str(current) / "exe") == want:
                return current
        except OSError:
            pass
        for children in sorted((proc / str(current) / "task").glob("*/children")):
            try:
                queue += [int(c) for c in children.read_text().split()]
            except (OSError, ValueError):
                pass
    return None


def pid_state(pid, proc=Path("/proc")):
    """"running", or "gone" when /proc has no live process `pid` (exited, or a zombie its parent has not reaped)."""
    try:
        stat = (proc / str(pid) / "stat").read_text()
    except OSError:
        return "gone"
    return "gone" if stat[stat.rfind(")") + 2:].startswith(("Z", "X")) else "running"


def describe_processes(state):
    """One line naming each process of a game and what it was doing: `state` maps a process name to {"pid", and
    "status" (the exit status we read, None while it runs) or "state" ("running", "gone")}."""
    parts = []
    for name, info in state.items():
        if info.get("pid") is None:
            parts.append(f"{name}: pid unknown")
        elif "status" in info:
            status = info["status"]
            parts.append(f"{name} (pid {info['pid']}): " + ("running" if status is None else f"exited, status {status}"))
        else:
            parts.append(f"{name} (pid {info['pid']}): {info['state']}")
    return "; ".join(parts)


class Game:
    """A Sunrise game in scratch folders under `folder`, started inside its display, stopped on exit."""

    def __init__(self, args, scenes, folder, bin_dir, env, game_args):
        self.args, self.scenes, self.folder = args, scenes, Path(folder)
        self.client, ctl = binaries(bin_dir)
        # A socket path must stay under ~100 bytes: a fresh folder of /tmp, removed after the run.
        self.sock_dir = Path(tempfile.mkdtemp(prefix="ssc-"))
        self.ctl = Sunrise(ctl, self.sock_dir / "ctl.sock", env)
        self.env, self.game_args, self.proc = env, game_args, None
        self.log = self.folder / "home" / "logs" / "latest.log"
        self.client_pid, self.before_cleanup, self.after_cleanup = None, None, None

    def processes(self):
        """What the game's processes were doing, by process: the gamescope wrapper we started (its exit status once
        it exited) and the sunrise-client in it (running or gone: gamescope reaps it, so its status is not ours to
        read); with --display current, sunrise-client is the process we started."""
        if self.proc is None:
            return {}
        if self.args.display == "current":
            return {"sunrise-client": {"pid": self.proc.pid, "status": self.proc.poll()}}
        return {"gamescope": {"pid": self.proc.pid, "status": self.proc.poll()},
                "sunrise-client": {"pid": self.client_pid,
                                   **({"state": pid_state(self.client_pid)} if self.client_pid else {})}}

    def __enter__(self):
        width, height = self.scenes["size"]
        command = [str(self.client), "--resources", str(self.args.resources), "--game-dir",
                   str(self.folder / "game"), "--home", str(self.folder / "home"), "--world", WORLD, "--offscreen",
                   "--width", str(width), "--height", str(height), "--control-socket", str(self.ctl.socket),
                   *self.game_args]
        self.proc = start_game(self.args, self.scenes, command, self.env, self.folder / "game-stdout.log",
                               self.folder / "game")
        limit = self.scenes["load_timeout_seconds"]
        try:
            if not wait_for_socket(self.ctl, self.proc, limit):
                raise RuntimeError(f"Sunrise did not open its control socket; see {self.folder / 'game-stdout.log'}")
            self.client_pid = find_descendant(self.proc.pid, self.client)
            self.ctl("wait-ready", int(limit), timeout=limit + 60)
        except BaseException:
            # __exit__ runs only after a successful __enter__: stop the game here.
            self.__exit__(None, None, None)
            raise
        return self.ctl

    def __exit__(self, *_):
        # Read before the quit and the stop below change it: whether a process had already exited on its own.
        self.before_cleanup = self.processes()
        try:
            if self.proc is not None:
                try:
                    self.ctl("quit", check=False, timeout=120)
                except (OSError, subprocess.TimeoutExpired):
                    pass
                stop_game(self.proc)
                self.after_cleanup = self.processes()
            if self.log.exists():
                shutil.copy(self.log, self.folder / "game.log")
        finally:
            shutil.rmtree(self.sock_dir, ignore_errors=True)
        return False


def data_version(resources):
    """The world data version the prepared resources were made for (`data_version` of their
    sunrise-resources.json), which options.txt's `version` line carries."""
    manifest = Path(resources) / "sunrise-resources.json"
    try:
        value = json.loads(manifest.read_text()).get("data_version")
    except (OSError, ValueError, AttributeError) as error:
        raise SystemExit(f"{manifest}: no readable prepared-resources manifest ({error})") from None
    if isinstance(value, bool) or not isinstance(value, int):
        raise SystemExit(f"{manifest}: no data_version")
    return value


def prepare_game_dir(scenes, game_dir, resources):
    game_dir.mkdir(parents=True)
    (game_dir / "options.txt").write_text(
        options_text({**scenes["options"], **FORCED_OPTIONS}, {"version": str(data_version(resources))}))
    (game_dir / "sunrise-graphics.txt").write_text(options_text(scenes["graphics"]))


def run_capture(args, scenes, side, bin_dir, extra_env, pack):
    """One side's run of one pack: every view captured in one game. Returns the run's record (also run.json)."""
    folder = fresh_folder(Path(args.out) / side / pack_key(pack), args.replace)
    game_dir = folder / "game"
    prepare_game_dir(scenes, game_dir, args.resources)
    generation = copy_world(args.out, game_dir, scenes)
    env = game_environment(folder, extra_env)
    staged_name, digest = (None, "none") if pack == "none" else stage_pack(pack, game_dir)
    if staged_name:
        env["SUNRISE_SHADER_PACK"] = staged_name
    client, _ = binaries(bin_dir)
    record = {"side": side, "pack": staged_name or "none", "pack_sha256": digest,
              "binary_sha256": sha256_file(client), "env": extra_env, "views": {}, "notes": [],
              "start_problems": ["the start checks never ran"], "resources_sha256": resources_digest(args.resources),
              "renderer": None, **generation}
    expected = settings_expected(scenes)
    game = Game(args, scenes, folder, bin_dir, env, [])
    # Read for `none` too: its moves must show in the log as well.
    watch = PackWatch(lambda: pack_events(game.log.read_text(errors="replace"), staged_name or "")
                      if game.log.exists() else [])
    try:
        with game as ctl:
            # The world opens where the player was saved (the first view's dimension): its load is expected.
            dimension = (ctl("state").get("dimension") or "").removeprefix("minecraft:")
            record["renderer"] = renderer_identity(ctl("status"))
            if staged_name:
                watch.world_opened()
            results = {}
            for line in start_commands(scenes):
                reply = ctl("command", line, check=False)
                results[line] = reply.get("result") if reply.get("success") else None
            record["start_problems"] = start_problems(scenes, results)
            ctl("key", "f1", "tap")
            run_views(ctl, scenes, folder, watch, staged_name, expected, dimension, record["views"], side,
                      pack_key(pack))
            # A load the log shows only now may have run during the last capture.
            time.sleep(1.0)
            late = watch.after_capture()
            if late and record["views"]:
                last = scenes["views"][len(record["views"]) - 1]["name"]
                record["views"][last]["problems"] += [f"after the last capture: {p}" for p in late]
    except (RuntimeError, OSError, subprocess.TimeoutExpired) as error:
        # The game died or stopped answering: the views not taken stay without a record; the next pack still runs.
        note = (f"stopped: {error}; before cleanup: {describe_processes(game.before_cleanup or {})}; "
                f"after cleanup: {describe_processes(game.after_cleanup or {})}")
        record["notes"].append(note)
        record["processes"] = {"before_cleanup": game.before_cleanup, "after_cleanup": game.after_cleanup}
        print(f"{side} {pack_key(pack)}: {note}", flush=True)
    finally:
        if staged_name and game.log.exists():
            prefix = f"shader pack {staged_name}: "
            record["pack_notes"] = [l[l.find(prefix):] for l in game.log.read_text(errors="replace").splitlines()
                                    if prefix in l]
        write_run(folder, record)
    return record


def run_world(args, scenes, bin_dir):
    """Generates the shared world with Sunrise from the scene's seed: visits every view so its chunks exist, goes
    back to the first view, and quits (which saves). The save is published to OUT/world/scenes, with a fresh
    generation id and the scene hash, only when every view loaded, the camera read back at the first view and the
    game exited cleanly."""
    out = Path(args.out)
    world = out / "world"
    # --replace first: it is also the way out of a published world that can't be read.
    if not args.replace and world_generation(out) is not None:
        raise SystemExit(f"{world} has a published world: pass --replace to make it again")
    scratch = fresh_folder(out / "build" / f"world-run-{uuid.uuid4().hex[:8]}", False)
    prepare_game_dir(scenes, scratch / "game", args.resources)
    env = game_environment(scratch, {})
    env.pop("SUNRISE_STILL")
    problems = []
    game = Game(args, scenes, scratch, bin_dir, env, ["--seed", str(scenes["seed"]), "--creative"])
    try:
        with game as ctl:
            ctl.command("gamemode spectator @a")
            for view in [*scenes["views"], scenes["views"][0]]:
                ctl.command(view_commands(view)[0])
                if not wait_loaded(ctl, view, scenes["load_timeout_seconds"]):
                    problems.append(f"view {view['name']} never finished loading")
                print(f"world {view['name']}: {'ok' if not problems else problems[-1]}", flush=True)
            camera = sunrise_camera(ctl("state"))
    except (RuntimeError, OSError, subprocess.TimeoutExpired) as error:
        raise SystemExit(f"world not published: {error} (see {scratch})") from None
    status = game.proc.returncode
    first = scenes["views"][0]
    if camera.get("dimension") != dimension_id(first["dimension"]) or max(
            abs(a - b) for a, b in zip(camera.get("pos") or [math.inf] * 3, first["pos"])) > POSITION_EPSILON:
        problems.append(f"the camera ended at {camera.get('dimension')} {camera.get('pos')}, not the first view")
    if status != 0:
        problems.append(f"the game exited with status {status}")
    save = scratch / "game" / "saves" / WORLD
    if not (save / "level.dat").exists():
        problems.append("the game saved no level.dat")
    if problems:
        raise SystemExit("world not published: " + "; ".join(problems) + f" (see {scratch})")
    publish_world(out, save, scenes, bin_dir)


def publish_world(out, save, scenes, bin_dir):
    """Publishes a saved world to OUT/world as a new generation: OUT/world/generations/<id>/ gets the save and its
    generation.json (the id, the scene hash, the build and the digest of the published save), whole, and only then
    OUT/world/current.json is pointed at it, by one atomic rename. Until that rename the previous generation stays
    the published one, and it is kept afterwards (a capture copying it at that moment still finds it whole)."""
    world = Path(out) / "world"
    if world.exists() and not (world / RUN_MARK).exists():
        raise SystemExit(f"{world} was not made by this tool; not publishing into it")
    world.mkdir(parents=True, exist_ok=True)
    (world / RUN_MARK).write_text("")
    world_id = uuid.uuid4().hex
    folder = world / "generations" / world_id
    folder.mkdir(parents=True)
    shutil.copytree(save, folder / WORLD, ignore=shutil.ignore_patterns("session.lock"))
    client, _ = binaries(bin_dir)
    (folder / "generation.json").write_text(json.dumps(
        {"world_id": world_id, "scene_hash": scene_hash(scenes), "seed": scenes["seed"],
         "binary_sha256": sha256_file(client), "save_sha256": staged_digest(folder / WORLD)}, indent=2) + "\n")
    pending = world / f"current.json.{world_id}"
    pending.write_text(json.dumps({"world_id": world_id}) + "\n")
    os.replace(pending, world / "current.json")
    print(f"world published: {folder / WORLD}")


