#!/usr/bin/env python3
"""Shader-pack scene suite: two Sunrise builds photograph the same fixed views, and every picture is compared pixel
for pixel.

The scene file (tools/shader-scenes/scenes.json, docs in tools/shader-scenes/README.md) names a seed, the picture
size, the capture clock, pinned options and gamerules, and views: a dimension, a camera, a time, a weather and
vanilla setup commands. Every run writes under one output folder:

    world/current.json, generations/ the shared world, generated by Sunrise (`world`), and which generation is live
    base/<pack>/<view>.png           the base build's pictures (`capture --side base`), with run.json and the log
    head/<pack>/<view>.png           the head build's pictures (`capture --side head`)
    report/                          the comparison (`compare`): index.html, report.md, report.json, diff/

    python3 tools/shader_scenes.py check
    python3 tools/shader_scenes.py world --out OUT --bin-dir BASE
    python3 tools/shader_scenes.py capture --out OUT --side base --bin-dir BASE --pack none --pack PACKS/BSL.zip
    python3 tools/shader_scenes.py capture --out OUT --side head --bin-dir HEAD --pack none --pack PACKS/BSL.zip
    python3 tools/shader_scenes.py compare --out OUT
    python3 tools/shader_scenes.py run --out OUT --base-bin-dir BASE --head-bin-dir HEAD --pack PACKS/BSL.zip

Each picture is `sunrise-ctl screenshot-sequence FRAMES STEP_MS`, under SUNRISE_STILL=1 with the world frozen: the
pack starts over and draws its frames on a set clock, so one build writes the same bytes every run and any pixel
that differs between base and head is the builds' difference. Packs are only loaded (copied into each game's
shaderpacks/), never read. Nothing here is committed: no pictures, worlds or packs.

Exit status: 0 every view valid and equal; 1 the comparison completed and some valid view differs; 2 some view
invalid or missing (`capture`: not every view recorded); 3 nothing compared: the run could not be set up or the
command line is wrong.
"""
